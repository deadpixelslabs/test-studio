function sanitize(value) {
  return String(value || '').trim().replace(/^Bearer\s+/i, '').replace(/^['"]|['"]$/g, '');
}

export default async function handler(req, res) {
  const groqKey = sanitize(process.env.GROQ_API_KEY);
  const geminiKey = sanitize(process.env.GEMINI_API_KEY);
  const model = process.env.GROQ_MODEL || 'openai/gpt-oss-20b';

  if (!groqKey) {
    return res.status(200).json({
      ok: false,
      version: '1.1.1',
      env: { groqKey: false, geminiKey: Boolean(geminiKey) },
      error: 'GROQ_API_KEY missing.',
    });
  }

  const started = Date.now();
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), 15000);
  try {
    const response = await fetch('https://api.groq.com/openai/v1/chat/completions', {
      method: 'POST',
      headers: { Authorization: `Bearer ${groqKey}`, 'Content-Type': 'application/json' },
      signal: controller.signal,
      body: JSON.stringify({
        model,
        messages: [{ role: 'user', content: 'Reply with exactly: OK' }],
        temperature: 0,
        reasoning_effort: 'low',
        max_completion_tokens: 32,
      }),
    });
    const raw = await response.text();
    res.status(200).json({
      ok: response.ok && Boolean(geminiKey),
      version: '1.1.1',
      env: { groqKey: true, geminiKey: Boolean(geminiKey) },
      groq: {
        model,
        status: response.status,
        latencyMs: Date.now() - started,
        preview: raw.slice(0, 180),
      },
      gemini: {
        model: process.env.GEMINI_IMAGE_MODEL || 'gemini-3.1-flash-image',
        configured: Boolean(geminiKey),
        note: 'No paid image is generated by diagnostics.',
      },
      note: 'Secret keys are never returned.',
    });
  } catch (error) {
    res.status(200).json({
      ok: false,
      version: '1.1.1',
      env: { groqKey: true, geminiKey: Boolean(geminiKey) },
      model,
      latencyMs: Date.now() - started,
      error: error?.message || String(error),
    });
  } finally {
    clearTimeout(timer);
  }
}
